import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  dailyRate,
  fit,
  modelDaily,
  parseAnalyticsCsv,
  type DayStats
} from './analytics.js';
import { DEFAULT_REACH } from './reach.js';

const fixture = readFileSync(
  new URL('./fixtures/analytics-synthetic.csv', import.meta.url),
  'utf8'
);

describe('parseAnalyticsCsv', () => {
  it('reads the synthetic export: one row per day, quoted thousands', () => {
    expect(parseAnalyticsCsv(fixture)).toEqual([
      {
        date: '2026-09-01',
        impressions: 1240,
        reactions: 52,
        comments: 11,
        reposts: 3
      },
      {
        date: '2026-09-02',
        impressions: 610,
        reactions: 19,
        comments: 4,
        reposts: 1
      },
      {
        date: '2026-09-03',
        impressions: 95,
        reactions: 3,
        comments: 0,
        reposts: 0
      }
    ]);
  });

  it('matches headers case-insensitively, in any order, ignoring a BOM, extra columns and blank lines', () => {
    const csv =
      '\uFEFFReposts,Clicks,Impressions,comments,Reactions,Date\r\n2,9,100,1,5,2026-01-01\r\n\r\n';
    expect(parseAnalyticsCsv(csv)).toEqual([
      {
        date: '2026-01-01',
        impressions: 100,
        reactions: 5,
        comments: 1,
        reposts: 2
      }
    ]);
  });

  it('names a missing column and a bad number', () => {
    expect(() => parseAnalyticsCsv('Date,Impressions\n2026-01-01,5\n')).toThrow(
      /missing column "reactions"/
    );
    expect(() =>
      parseAnalyticsCsv(
        'Date,Impressions,Reactions,Comments,Reposts\n2026-01-01,many,1,1,1\n'
      )
    ).toThrow(/line 2: "impressions" is not a number/);
  });
});

describe('fit', () => {
  /** A series generated by the model itself with known constants, at fixed daily engagement rates. */
  function synthetic(testSlice: number, expansion: number): DayStats[] {
    const c = { ...DEFAULT_REACH, testSlice, expansion };
    const at = (rates: number[], impressions: number[]): DayStats[] =>
      rates.map((r, i) => ({
        date: `d${i}`,
        impressions: impressions[i]!,
        reactions: r * impressions[i]!,
        comments: 0,
        reposts: 0
      }));
    const rates = [0.08, 0.04, 0.02];
    return at(rates, modelDaily(c, 3000, at(rates, [1000, 1000, 1000])));
  }

  it('weights comments and reposts above reactions in the daily rate', () => {
    const base = {
      date: 'd',
      impressions: 100,
      reactions: 0,
      comments: 0,
      reposts: 0
    };
    expect(dailyRate({ ...base, comments: 1 })).toBeGreaterThan(
      dailyRate({ ...base, reactions: 1 })
    );
    expect(dailyRate({ ...base, impressions: 0, reactions: 1 })).toBe(1);
  });

  it('moves test slice and expansion toward the constants that produced the series', () => {
    const days = synthetic(0.15, 0.6);
    const r = fit(days, 3000);
    expect(r.testSlice).toBeCloseTo(0.15, 1);
    expect(r.expansion).toBeCloseTo(0.6, 1);
    expect(r.after).toBeLessThan(r.before);
    expect(r.after).toBeLessThan(0.05);
  });

  it('keeps the defaults when they already explain the series', () => {
    const days = synthetic(DEFAULT_REACH.testSlice, DEFAULT_REACH.expansion);
    const r = fit(days, 3000);
    expect(r.testSlice).toBeCloseTo(DEFAULT_REACH.testSlice, 2);
    expect(r.expansion).toBeCloseTo(DEFAULT_REACH.expansion, 1);
  });

  it('rejects an empty series', () => {
    expect(() => fit([], 3000)).toThrow(/no days/);
  });
});
